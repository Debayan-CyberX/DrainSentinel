from pydantic import BaseModel, Field
from typing import List, Optional


class DraftRecommendation(BaseModel):
    priority: str = Field(..., description="Suggested dispatch priority (e.g. 'P1 - Critical', 'P2 - High')")
    suggested_crew: str = Field(..., description="Recommended municipal crew specialty")
    recommended_actions: List[str] = Field(default_factory=list, description="Specific field steps recommended for crew")
    equipment_needed: List[str] = Field(default_factory=list, description="Tools and machinery needed")
    urgency: str = Field(..., description="Response window (e.g. 'Immediate (within 2 hours)', 'Same day')")


class DrainIntelligence(BaseModel):
    drain_id: str = Field(..., description="Unique drain asset identifier")
    drain_name: str = Field(..., description="Asset name and landmark")
    generated_at: str = Field(..., description="ISO 8601 generation timestamp")
    is_ai_generated: bool = Field(..., description="True if generated by an LLM, False if generated by deterministic fallback")
    provider: str = Field(..., description="Name of the model or fallback engine used")
    summary: str = Field(..., description="Synthesized operational narrative consolidating all incident reports and telemetry")
    risk_factor_explanation: List[str] = Field(
        default_factory=list,
        description="Plain-language explanation of structured mathematical factors driving the deterministic score"
    )
    missing_or_conflicting_info: List[str] = Field(
        default_factory=list,
        description="Audit flags identifying missing evidence, contradictory reports, or stale telemetry"
    )
    draft_recommendation: DraftRecommendation = Field(..., description="Proposed inspection and work-order plan")
    human_approval_required: bool = Field(
        default=True,
        description="Explicit advisory flag requiring human municipal operator approval before dispatch"
    )
    disclaimer: str = Field(
        default="Simulated Municipal Data. AI draft is strictly advisory; human operator approval is required for all official dispatches.",
        description="Regulatory and safety advisory notice"
    )
